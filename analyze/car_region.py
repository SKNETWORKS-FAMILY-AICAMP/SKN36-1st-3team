# 시도 → 시군구 → 월별 추세 → 차종 → 용도

import sqlite3
import pandas as pd
import matplotlib.pyplot as plt

from models.visualization import line_plot, bar_plot, heatmap_plot


# DB 불러오기
with sqlite3.connect("database/car.db") as conn:
    df = pd.read_sql(
        "SELECT * FROM car_registration_region",
        conn
    )

df["month"] = pd.to_datetime(df["month"])
df["count"] = pd.to_numeric(df["count"])

# 같은 이름의 중구, 서구 등 구분
df["region"] = df["sido"] + " " + df["sigungu"]


# ============================================================
# 1. 시도별 자동차 등록대수
# ============================================================

bar_plot(
    df,
    "sido",
    "count",
    "시도별 자동차 등록대수"
)


# ============================================================
# 2. 시군구별 자동차 등록대수 TOP 20
# ============================================================

bar_plot(
    df,
    "region",
    "count",
    "시군구별 자동차 등록대수 TOP 20",
    top_n=20
)


# ============================================================
# 3. 월별 전국 자동차 등록 추세
# ============================================================

line_plot(
    df,
    "month",
    "count",
    "월별 전국 자동차 등록대수 추세"
)


# ============================================================
# 4. 차종별 자동차 등록대수
# ============================================================

bar_plot(
    df,
    "vehicle_type",
    "count",
    "차종별 자동차 등록대수"
)


# ============================================================
# 5. 용도별 자동차 등록대수
# ============================================================

bar_plot(
    df,
    "usage",
    "count",
    "용도별 자동차 등록대수"
)


# ============================================================
# 6. 특정 시도 분석
# ============================================================

SIDO = "서울"

sido_df = df[df["sido"] == SIDO]

bar_plot(
    sido_df,
    "sigungu",
    "count",
    f"{SIDO} 시군구별 자동차 등록대수"
)


# ============================================================
# 7. 특정 시군구 월별 추세
# ============================================================

SIGUNGU = "강남구"

region_df = df[
    (df["sido"] == SIDO) &
    (df["sigungu"] == SIGUNGU)
]

line_plot(
    region_df,
    "month",
    "count",
    f"{SIDO} {SIGUNGU} 월별 자동차 등록대수 추세"
)


# ============================================================
# 8. 특정 지역 차종별 비교
# ============================================================

bar_plot(
    region_df,
    "vehicle_type",
    "count",
    f"{SIDO} {SIGUNGU} 차종별 자동차 등록대수"
)


# ============================================================
# 9. 특정 지역 용도별 비교
# ============================================================

bar_plot(
    region_df,
    "usage",
    "count",
    f"{SIDO} {SIGUNGU} 용도별 자동차 등록대수"
)